    "You will be given a structured text description of an engineering diagram extracted by vision analysis.\n"
    "Your job is to trace every process fluid present from its source to its destination.\n\n"
    "HOW TO RECONSTRUCT A PATH -- the evidence you receive does not hand you a pre-assembled "
    "sequence; you must infer one:\n"
    "- The VALVE AND FITTING SURVEY lists each fitting with a 'Line:' pipe spec. Fittings "
    "sharing the SAME pipe spec are on the same physical segment -- group them together.\n"
    "- Where the pipe spec CHANGES between two fittings that are otherwise associated (e.g. "
    "both near the same named stream or piece of equipment), that change usually marks a "
    "segment boundary -- often at a piece of major equipment, a filter, or a control valve.\n"
    "- Use the CONTEXT ANALYSIS section's named PROCESS STREAMS and MAJOR EQUIPMENT as anchor "
    "points: a stream name near a supply/inlet connection is likely the SOURCE; a stream name "
    "near a vent/drain/flare label is likely the DESTINATION.\n"
    "- Fitting types themselves carry directional information -- a drain or vent fitting marks "
    "an endpoint; a filter or control valve marks a midpoint the fluid passes through.\n"
    "- USE THE STREAM'S OWN NAME AS EVIDENCE OF ITS IDENTITY before concluding it's unknown. "
    "A stream named '<X> DRAIN' or '<X> VENT' is draining/venting fluid X -- it is not a "
    "separate mystery substance, even if its own path segment is short or poorly connected. "
    "A stream named 'ALTERNATE <X> SUPPLY', 'BACKUP <X>', or 'SECONDARY <X>' is the same fluid "
    "X as the primary supply, routed through a different/redundant line. Only fall back to "
    "UNKNOWN FLUID when the name itself gives no such clue AND no equipment/connectivity "
    "evidence helps either.\n"
    "- Build the PATH by ordering the fittings/segments you can place with reasonable confidence "
    "from source-side to destination-side. It is fine for a path to be partial.\n\n"
    "RULES:\n"
    "- Do the inference above using ONLY the evidence provided -- do not invent a fitting, "
    "line spec, or connection that isn't present in the material, even to complete a gap.\n"
